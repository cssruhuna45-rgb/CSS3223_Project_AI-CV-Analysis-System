package com.aiinterview.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

import java.time.LocalDateTime;

/**
 * Durable record of a candidate's personalized learning roadmap.
 *
 * <p>Generated by the AI service from interview weaknesses, category scores,
 * and skill gap analysis, then persisted in PostgreSQL so candidates can
 * track their 14-day upskilling progress across sessions and devices.
 */
@Entity
@Table(
        name = "learning_roadmaps",
        indexes = {
                @Index(
                        name = "idx_learning_roadmaps_user_created",
                        columnList = "user_id, created_at DESC"
                ),
                @Index(
                        name = "idx_learning_roadmaps_session",
                        columnList = "session_id"
                )
        }
)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@ToString(exclude = {"user"})
@EqualsAndHashCode(of = "id")
public class LearningRoadmap {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @Column(name = "session_id")
    private String sessionId;

    @Column(name = "target_role")
    private String targetRole;

    @Column(name = "job_field")
    private String jobField;

    @Column(name = "title", nullable = false)
    private String title;

    @Column(name = "summary", columnDefinition = "TEXT")
    private String summary;

    @Column(name = "duration_days", nullable = false)
    @Builder.Default
    private Integer durationDays = 14;

    @Column(name = "overall_score")
    private Integer overallScore;

    /**
     * Complete JSON payload returned by the AI roadmap generator,
     * containing days, milestones, tasks, and recommended resources.
     */
    @Column(name = "roadmap_json", nullable = false, columnDefinition = "TEXT")
    private String roadmapJson;

    /**
     * Stored JSON array of completed day numbers, e.g. "[1, 2, 5]".
     */
    @Column(name = "completed_days_json", columnDefinition = "TEXT")
    private String completedDaysJson;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    @PrePersist
    protected void onCreate() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
        if (durationDays == null) {
            durationDays = 14;
        }
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }
}
