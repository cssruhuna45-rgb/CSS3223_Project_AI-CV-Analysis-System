-- Persistent storage for 14-day learning roadmaps.
--
-- Generated from candidate interview feedback and skill gaps,
-- providing a structured day-by-day upskilling curriculum.

CREATE TABLE learning_roadmaps (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id             bigint NOT NULL,
    session_id          character varying(255),
    target_role         character varying(255),
    job_field           character varying(255),
    title               character varying(255) NOT NULL,
    summary             text,
    duration_days       integer NOT NULL DEFAULT 14,
    overall_score       integer,
    roadmap_json        text NOT NULL,
    completed_days_json text,
    created_at          timestamp(6) without time zone NOT NULL,
    updated_at          timestamp(6) without time zone,

    CONSTRAINT learning_roadmaps_pkey PRIMARY KEY (id),

    CONSTRAINT fk_learning_roadmaps_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,

    CONSTRAINT learning_roadmaps_duration_check
        CHECK (duration_days > 0 AND duration_days <= 60),

    CONSTRAINT learning_roadmaps_score_check
        CHECK (overall_score IS NULL OR (overall_score >= 0 AND overall_score <= 100))
);

CREATE INDEX idx_learning_roadmaps_user_created
    ON learning_roadmaps (user_id, created_at DESC);

CREATE INDEX idx_learning_roadmaps_session
    ON learning_roadmaps (session_id);
