-- A job's fixed interview: required skills, the recruiter's chosen
-- question count, and the approved questions every candidate is asked.
--
-- Until now a job interview was written fresh for each candidate from
-- their CV, so two candidates for the same job were asked different
-- things and their scores were not really comparable. A job now has a
-- question set the recruiter reviews and approves; every candidate is
-- asked exactly those questions, in order, and graded against the same
-- saved key points. Personal practice is unchanged and stays adaptive.
--
-- Numbered V10, not V9: V9 is taken by V9__password_recovery.sql on the
-- password-recovery branch, and Flyway refuses two scripts with one
-- version.

-- ----------------------------------------------------------------
-- Job settings
-- ----------------------------------------------------------------

-- 5 to 10, chosen by the recruiter. Jobs created before this migration
-- get 5, the length every interview had until now. They have no
-- questions yet, so they show as not ready until some are approved.
ALTER TABLE job_postings
    ADD COLUMN question_count integer DEFAULT 5 NOT NULL,
    ADD COLUMN questions_approved_at timestamp(6) without time zone,
    ADD COLUMN questions_approved_by bigint;

ALTER TABLE job_postings
    ADD CONSTRAINT ck_job_postings_question_count
        CHECK (question_count BETWEEN 5 AND 10);

-- Kept when the approving account is deleted; the approval still
-- happened.
ALTER TABLE job_postings
    ADD CONSTRAINT fk_job_postings_questions_approved_by
        FOREIGN KEY (questions_approved_by) REFERENCES users (id) ON DELETE SET NULL;

-- Normalised (trimmed, lower case, no repeats), in the order the
-- recruiter gave them. Jobs from before this migration have none and
-- must be given some before questions can be generated.
CREATE TABLE job_posting_required_skills (
    job_posting_id bigint NOT NULL,
    position       integer NOT NULL,
    skill          character varying(100) NOT NULL,

    CONSTRAINT job_posting_required_skills_pkey PRIMARY KEY (job_posting_id, position),

    CONSTRAINT fk_job_posting_required_skills_job
        FOREIGN KEY (job_posting_id) REFERENCES job_postings (id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------
-- Questions
-- ----------------------------------------------------------------

CREATE TABLE job_questions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    job_posting_id  bigint NOT NULL,

    -- 1-based order the question is asked in.
    position        integer NOT NULL,

    question_text   text NOT NULL,
    difficulty      character varying(16) NOT NULL,
    topic           character varying(120),

    -- AI: written by the generator and not changed since.
    -- RECRUITER: written or edited by the recruiter.
    source          character varying(16) NOT NULL,

    created_at      timestamp(6) without time zone NOT NULL,
    updated_at      timestamp(6) without time zone,

    CONSTRAINT job_questions_pkey PRIMARY KEY (id),

    -- Deferred, so a reorder can swap positions inside one transaction.
    CONSTRAINT uk_job_questions_position
        UNIQUE (job_posting_id, position) DEFERRABLE INITIALLY DEFERRED,

    CONSTRAINT ck_job_questions_difficulty
        CHECK (difficulty IN ('easy', 'medium', 'hard')),

    CONSTRAINT ck_job_questions_source
        CHECK (source IN ('AI', 'RECRUITER')),

    CONSTRAINT fk_job_questions_job
        FOREIGN KEY (job_posting_id) REFERENCES job_postings (id) ON DELETE CASCADE
);

-- What a complete answer to the question must cover. The grader
-- compares every candidate's answer against these, and they are never
-- sent to a candidate.
CREATE TABLE job_question_key_points (
    question_id bigint NOT NULL,
    position    integer NOT NULL,
    key_point   character varying(300) NOT NULL,

    CONSTRAINT job_question_key_points_pkey PRIMARY KEY (question_id, position),

    CONSTRAINT fk_job_question_key_points_question
        FOREIGN KEY (question_id) REFERENCES job_questions (id) ON DELETE CASCADE
);
