-- Candidate applications for a job, and the recruiter's decision on
-- each one.
--
-- Until now an invite code took a candidate straight into the
-- interview, so a recruiter met every candidate as a finished result
-- and had no say in who sat the assessment. A candidate now applies
-- with a chosen CV and explicit consent to share it; the recruiter
-- reads the application and shortlists or rejects by hand; only a
-- shortlisted candidate can start the job's approved interview.
--
-- Numbered V11, not V9 or V10: V9 is taken by V9__password_recovery.sql
-- on the password-recovery branch and V10 by V10__job_questions.sql,
-- and Flyway refuses two scripts with one version.
--
-- Existing data is untouched. Interviews already taken through an
-- invite code keep their rows and stay visible to their recruiter with
-- no application behind them; job_application_id is nullable for
-- exactly that reason.

-- ----------------------------------------------------------------
-- Applications
-- ----------------------------------------------------------------

CREATE TABLE job_applications (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,

    job_posting_id         bigint NOT NULL,
    candidate_id           bigint NOT NULL,

    -- The CV as chosen at application time. RESTRICT, not CASCADE:
    -- deleting a CV a recruiter has reviewed would destroy the
    -- evidence a hiring decision was made on, so the delete is refused
    -- while any application still points at it.
    submitted_resume_id    bigint NOT NULL,

    -- The analysis the recruiter was shown, copied verbatim from the
    -- AI service's JSON. A copy rather than a join to resume_analysis,
    -- which is replaced whenever a CV is re-analysed.
    analysis_snapshot      text,

    -- Proof of consent: the candidate ticked the box, when, and which
    -- wording they accepted. Always true on a stored row.
    consent_granted        boolean NOT NULL,
    consent_at             timestamp(6) without time zone,
    consent_version        character varying(16),

    -- Deterministic skill match, computed once at submission.
    -- Decision support only; nothing automatic reads it. Null means it
    -- could not be computed, which is shown as "not available" rather
    -- than as 0%.
    match_percentage       integer,
    required_skill_count   integer,

    status                 character varying(16) NOT NULL,

    applied_at             timestamp(6) without time zone NOT NULL,
    decided_at             timestamp(6) without time zone,
    decided_by             bigint,
    interview_completed_at timestamp(6) without time zone,

    created_at             timestamp(6) without time zone NOT NULL,
    updated_at             timestamp(6) without time zone,

    CONSTRAINT job_applications_pkey PRIMARY KEY (id),

    -- One application per candidate per job. In the database, not only
    -- in Java: two submits racing each other would both pass a
    -- Java-side check and leave a recruiter with the same candidate
    -- twice.
    CONSTRAINT uk_job_applications_job_candidate
        UNIQUE (job_posting_id, candidate_id),

    CONSTRAINT ck_job_applications_status
        CHECK (status IN ('APPLIED', 'SHORTLISTED', 'REJECTED', 'INTERVIEWED')),

    CONSTRAINT ck_job_applications_match_percentage
        CHECK (match_percentage IS NULL OR match_percentage BETWEEN 0 AND 100),

    -- An application that was never consented to must not exist.
    CONSTRAINT ck_job_applications_consent
        CHECK (consent_granted),

    -- A decided application records who decided and when; one still
    -- under review records neither.
    CONSTRAINT ck_job_applications_decision_recorded
        CHECK (
            (status = 'APPLIED' AND decided_at IS NULL)
            OR (status <> 'APPLIED' AND decided_at IS NOT NULL)
        ),

    CONSTRAINT fk_job_applications_job
        FOREIGN KEY (job_posting_id) REFERENCES job_postings (id) ON DELETE CASCADE,

    CONSTRAINT fk_job_applications_candidate
        FOREIGN KEY (candidate_id) REFERENCES users (id) ON DELETE CASCADE,

    CONSTRAINT fk_job_applications_resume
        FOREIGN KEY (submitted_resume_id) REFERENCES resumes (id) ON DELETE RESTRICT,

    -- Kept when the deciding account is deleted; the decision still
    -- happened.
    CONSTRAINT fk_job_applications_decided_by
        FOREIGN KEY (decided_by) REFERENCES users (id) ON DELETE SET NULL
);

-- The recruiter's applicant list: one job, best match first. DESC and
-- NULLS LAST so the order the list is read in is the order the index
-- already holds.
CREATE INDEX idx_job_applications_job_match
    ON job_applications (job_posting_id, match_percentage DESC NULLS LAST);

-- The candidate's own applications, newest first.
CREATE INDEX idx_job_applications_candidate
    ON job_applications (candidate_id, applied_at DESC);

-- ----------------------------------------------------------------
-- Match results
--
-- Three separate lists so a related skill can never be read as a
-- match. No primary key: these are JPA element collections, replaced
-- wholesale rather than updated row by row.
-- ----------------------------------------------------------------

CREATE TABLE job_application_matched_skills (
    application_id bigint NOT NULL,
    skill          character varying(100) NOT NULL,

    CONSTRAINT fk_job_application_matched_skills
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_application_matched_skills
    ON job_application_matched_skills (application_id);

CREATE TABLE job_application_related_skills (
    application_id bigint NOT NULL,
    skill          character varying(100) NOT NULL,

    CONSTRAINT fk_job_application_related_skills
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_application_related_skills
    ON job_application_related_skills (application_id);

CREATE TABLE job_application_missing_skills (
    application_id bigint NOT NULL,
    skill          character varying(100) NOT NULL,

    CONSTRAINT fk_job_application_missing_skills
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_application_missing_skills
    ON job_application_missing_skills (application_id);

-- ----------------------------------------------------------------
-- Interview attempt -> application
-- ----------------------------------------------------------------

-- Which application this interview is the attempt for. Null for the
-- personal practice interviews a candidate starts on their own, and
-- for job interviews taken through an invite code before this
-- migration.
ALTER TABLE interview_sessions
    ADD COLUMN job_application_id bigint;

ALTER TABLE interview_sessions
    ADD CONSTRAINT fk_interview_sessions_application
        FOREIGN KEY (job_application_id) REFERENCES job_applications (id) ON DELETE SET NULL;

-- One attempt per application, the whole point of a comparable
-- assessment. This is also what makes a double-clicked start safe:
-- the eligibility check resumes the existing attempt, and if two
-- requests race past it anyway the second insert is refused here
-- rather than giving one candidate two goes.
CREATE UNIQUE INDEX uk_interview_sessions_application
    ON interview_sessions (job_application_id)
    WHERE job_application_id IS NOT NULL;
