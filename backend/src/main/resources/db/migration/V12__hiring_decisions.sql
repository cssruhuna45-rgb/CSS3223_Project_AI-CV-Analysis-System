-- The recruiter's final answer on an interviewed candidate, whether it
-- has been announced, and the in-app notification that announces it.
--
-- Until now the workflow ended at INTERVIEWED: a candidate finished the
-- assessment and then heard nothing, because there was nowhere to
-- record whether they got the job. A recruiter can now decide, keep
-- that decision private while they think, and publish it deliberately;
-- only then does the candidate see it.
--
-- The decision is kept apart from job_applications.status on purpose.
-- An application stays INTERVIEWED - that is how far the candidate got
-- - while the hiring outcome lives here. Collapsing the two would lose
-- the difference between "not yet decided" and "not yet interviewed".
--
-- Numbered V12, after V11__job_applications.sql. V9 remains free for
-- V9__password_recovery.sql on the password-recovery branch.
--
-- Existing data is untouched. Every application that has already been
-- interviewed simply has no row here, which reads as "awaiting
-- recruiter decision". Nobody is retrospectively marked selected or
-- not selected.

-- ----------------------------------------------------------------
-- Hiring decisions
-- ----------------------------------------------------------------

CREATE TABLE hiring_decisions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,

    -- One decision per application. A double-clicked save must not
    -- leave a candidate with two conflicting outcomes, and the
    -- constraint is what guarantees it under a race rather than the
    -- Java check alone.
    application_id     bigint NOT NULL,

    decision           character varying(16) NOT NULL,
    publication_status character varying(16) NOT NULL,

    -- The recruiter's private reasoning. No candidate-facing endpoint
    -- selects this column.
    internal_notes     text,

    -- What the candidate reads, once published.
    candidate_feedback text,

    decided_by         bigint,
    decided_at         timestamp(6) without time zone,

    -- The single thing that makes a decision visible to the candidate.
    published_at       timestamp(6) without time zone,

    created_at         timestamp(6) without time zone NOT NULL,
    updated_at         timestamp(6) without time zone,

    CONSTRAINT hiring_decisions_pkey PRIMARY KEY (id),

    CONSTRAINT uk_hiring_decisions_application UNIQUE (application_id),

    CONSTRAINT ck_hiring_decisions_decision
        CHECK (decision IN ('PENDING', 'SELECTED', 'NOT_SELECTED')),

    CONSTRAINT ck_hiring_decisions_publication
        CHECK (publication_status IN ('DRAFT', 'PUBLISHED')),

    -- A published decision must be an actual answer and must carry the
    -- moment it was announced. "Published PENDING" would notify a
    -- candidate about nothing, and a published row with no timestamp
    -- could not be audited.
    CONSTRAINT ck_hiring_decisions_published_is_answered
        CHECK (
            publication_status = 'DRAFT'
            OR (decision IN ('SELECTED', 'NOT_SELECTED') AND published_at IS NOT NULL)
        ),

    -- A draft has not been announced, so it has no publication time.
    CONSTRAINT ck_hiring_decisions_draft_not_published
        CHECK (publication_status = 'PUBLISHED' OR published_at IS NULL),

    CONSTRAINT fk_hiring_decisions_application
        FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE,

    -- Kept when the deciding account is deleted; the decision still
    -- happened.
    CONSTRAINT fk_hiring_decisions_decided_by
        FOREIGN KEY (decided_by) REFERENCES users (id) ON DELETE SET NULL
);

-- ----------------------------------------------------------------
-- Audit trail
--
-- Append-only: a hiring decision is the kind of record somebody later
-- asks questions about, so each step is added rather than overwriting
-- the one before. Nothing in the application updates or deletes these.
-- ----------------------------------------------------------------

CREATE TABLE hiring_decision_events (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    hiring_decision_id bigint NOT NULL,

    action             character varying(16) NOT NULL,
    decision           character varying(16) NOT NULL,
    publication_status character varying(16) NOT NULL,

    actor_id           bigint,
    created_at         timestamp(6) without time zone NOT NULL,

    CONSTRAINT hiring_decision_events_pkey PRIMARY KEY (id),

    CONSTRAINT ck_hiring_decision_events_action
        CHECK (action IN ('DRAFTED', 'PUBLISHED', 'CORRECTED')),

    CONSTRAINT ck_hiring_decision_events_decision
        CHECK (decision IN ('PENDING', 'SELECTED', 'NOT_SELECTED')),

    CONSTRAINT ck_hiring_decision_events_publication
        CHECK (publication_status IN ('DRAFT', 'PUBLISHED')),

    CONSTRAINT fk_hiring_decision_events_decision
        FOREIGN KEY (hiring_decision_id) REFERENCES hiring_decisions (id) ON DELETE CASCADE,

    CONSTRAINT fk_hiring_decision_events_actor
        FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_hiring_decision_events_decision
    ON hiring_decision_events (hiring_decision_id, created_at);

-- ----------------------------------------------------------------
-- In-app notifications
--
-- The project had none: only transient toasts, gone on reload. A
-- published hiring decision is exactly what a candidate must not miss
-- because they were looking elsewhere. This is the minimum that fixes
-- that - no email, no push, no delivery infrastructure.
-- ----------------------------------------------------------------

CREATE TABLE notifications (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,

    recipient_id       bigint NOT NULL,

    type               character varying(32) NOT NULL,
    title              character varying(150) NOT NULL,
    message            text NOT NULL,

    -- What it is about, so the UI can link to it. Carries no outcome
    -- itself: ownership is checked again when the result is read.
    job_application_id bigint,

    read_at            timestamp(6) without time zone,
    created_at         timestamp(6) without time zone NOT NULL,

    CONSTRAINT notifications_pkey PRIMARY KEY (id),

    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_id) REFERENCES users (id) ON DELETE CASCADE,

    CONSTRAINT fk_notifications_application
        FOREIGN KEY (job_application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

-- The candidate's own list, newest first.
CREATE INDEX idx_notifications_recipient
    ON notifications (recipient_id, created_at DESC);

-- One notification per application per publication. A replayed publish
-- must not notify the candidate twice; the service is idempotent, and
-- this is the guarantee underneath it.
CREATE UNIQUE INDEX uk_notifications_hiring_decision
    ON notifications (job_application_id, type)
    WHERE job_application_id IS NOT NULL;
