-- Baseline schema: everything the application had before Flyway.
--
-- Generated from the running development database with
--   pg_dump --schema-only --no-owner --no-privileges
-- and then tidied: the dump's SET/\restrict preamble is dropped, and
-- Hibernate's generated constraint names (uk6dotkott2kjsp8vw4d0m25fb7
-- and friends) are replaced with readable ones. Hibernate's
-- ddl-auto=validate checks tables, columns and types - never
-- constraint names - so the rename is safe.
--
-- IMPORTANT: on a database that already existed before Flyway was
-- introduced, this file never runs. Such a database is stamped at
-- version 1 by spring.flyway.baseline-on-migrate, because its schema
-- is already exactly what this file would have produced. Only V2 and
-- later apply there. Anything that must reach BOTH an existing and a
-- fresh database therefore belongs in a later migration, not here.


-- ==================================================================
-- users
-- ==================================================================

CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) without time zone NOT NULL,
    email      character varying(255) NOT NULL,
    name       character varying(255) NOT NULL,
    password   character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone,
    role       character varying(32) DEFAULT 'CANDIDATE' NOT NULL,
    is_active  boolean DEFAULT true NOT NULL,

    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_role_check
        CHECK (role IN ('CANDIDATE', 'RECRUITER', 'ADMIN'))
);


-- ==================================================================
-- resumes
-- ==================================================================

CREATE TABLE resumes (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    content_type       character varying(255) NOT NULL,
    extracted_text     text,
    file_path          character varying(255) NOT NULL,
    file_size          bigint NOT NULL,
    original_file_name character varying(255) NOT NULL,
    processing_status  character varying(255) NOT NULL,
    stored_file_name   character varying(255) NOT NULL,
    updated_at         timestamp(6) without time zone,
    uploaded_at        timestamp(6) without time zone NOT NULL,
    user_id            bigint NOT NULL,

    CONSTRAINT resumes_pkey PRIMARY KEY (id),
    CONSTRAINT fk_resumes_user FOREIGN KEY (user_id) REFERENCES users (id)
);


-- ==================================================================
-- resume_analysis
--
-- score is kept nullable on purpose: the AI service stopped returning
-- one, and a NOT NULL column here used to fail every analysis insert.
-- ==================================================================

CREATE TABLE resume_analysis (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    score     integer,
    summary   text,
    resume_id bigint NOT NULL,

    CONSTRAINT resume_analysis_pkey PRIMARY KEY (id),
    CONSTRAINT uk_resume_analysis_resume UNIQUE (resume_id),
    CONSTRAINT fk_resume_analysis_resume
        FOREIGN KEY (resume_id) REFERENCES resumes (id)
);


-- ==================================================================
