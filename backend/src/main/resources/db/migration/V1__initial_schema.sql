-- the fields. They are recreated here so that a fresh database is
-- structurally identical to the existing ones, and so that dropping
-- them later is a deliberate migration rather than an accidental
-- divergence between environments. ddl-auto=validate ignores tables
-- that no entity maps.
-- ==================================================================

