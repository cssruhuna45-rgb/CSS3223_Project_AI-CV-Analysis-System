-- Skill gap analyses, kept per CV.
--
-- Until now a skill gap analysis lived only in the browser's
-- sessionStorage. Closing the tab lost it, and a candidate with
-- several CVs had no way to look back at what any of them had been
-- compared against. The CV Analysis page now lists a candidate's
-- uploads and the analyses stored against each one, which needs them
-- to outlive the tab.
--
-- Re-running the analysis is not free and not repeatable: the AI
-- service extracts the candidate's skills with a Gemini call before
-- the deterministic matching happens, so a second run of the same CV
-- and field can return a different set of skills and a different
-- percentage. Showing a stored result is therefore not just faster,
-- it is the only way the page can show the candidate the same numbers
-- they were given the first time.
--
-- One row per CV per job field, replaced when that pair is analysed
-- again: the page shows "the current analysis of this CV for this
-- field", not a history of attempts. A candidate who compares one CV
-- against three fields gets three rows.

CREATE TABLE skill_gap_analyses (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,

    resume_id        bigint NOT NULL,

    -- The field as the AI service names it (software_engineering) and
    -- as it is shown (Software Engineering). The display name is
    -- stored rather than looked up so an old row still reads
    -- correctly after the field list is edited.
    job_field        character varying(64) NOT NULL,
    job_field_name   character varying(128) NOT NULL,

    -- Denormalised for the list: the page shows every analysis of a CV
    -- with its percentage, and should not have to parse each snapshot
    -- to draw that.
    match_percentage integer NOT NULL,
    gap_percentage   integer NOT NULL,

    summary          text,

    -- The AI service's response, copied verbatim, in the same shape
    -- the browser receives from a live analysis. The stored view and
    -- the fresh one then render through the same code, and a new
    -- field in that response needs no migration to be kept.
    result_json      text NOT NULL,

    analysed_at      timestamp(6) without time zone NOT NULL,

    CONSTRAINT skill_gap_analyses_pkey PRIMARY KEY (id),

    -- In the database, not only in Java: two analyses of the same CV
    -- and field racing each other would both pass a Java-side check
    -- and leave the candidate with the same field listed twice.
    CONSTRAINT uk_skill_gap_analyses_resume_field
        UNIQUE (resume_id, job_field),

    -- CASCADE, unlike resume_analysis and unlike the RESTRICT that
    -- guards a submitted CV in V11. Nothing here is evidence a
    -- recruiter saw or a decision was made on - it is derived from the
    -- CV and means nothing without it - so when the CV goes, these go
    -- with it rather than leaving the delete to remember them.
    CONSTRAINT fk_skill_gap_analyses_resume
        FOREIGN KEY (resume_id) REFERENCES resumes (id)
        ON DELETE CASCADE
);


-- The page's one query: every analysis of one CV, newest first.
CREATE INDEX idx_skill_gap_analyses_resume
    ON skill_gap_analyses (resume_id, analysed_at DESC);
