-- Job postings and invite codes.
--
-- Approval (V6) decides WHO may act as a recruiter. This decides WHAT
-- an approved recruiter sees. Until now that was every interview on the
-- platform - other recruiters' candidates, and candidates practising
-- on their own who never chose to share anything.
--
-- A recruiter now creates a job and gets an invite code for it. A
-- candidate who enters the code agrees to share that one interview with
-- that recruiter, and the dashboard shows only interviews linked to the
-- recruiter's own jobs. Interviews without a job stay private.

CREATE TABLE job_postings (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    recruiter_id    bigint NOT NULL,
    title           character varying(150) NOT NULL,
    company         character varying(150),
    job_field       character varying(64) NOT NULL,
    job_description text NOT NULL,
    invite_code     character varying(16) NOT NULL,
    is_open         boolean DEFAULT true NOT NULL,
    created_at      timestamp(6) without time zone NOT NULL,
    updated_at      timestamp(6) without time zone,

    CONSTRAINT job_postings_pkey PRIMARY KEY (id),

    CONSTRAINT uk_job_postings_invite_code UNIQUE (invite_code),

    -- A recruiter's jobs go when the account goes.
    CONSTRAINT fk_job_postings_recruiter
        FOREIGN KEY (recruiter_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_postings_recruiter
    ON job_postings (recruiter_id, created_at DESC);


-- Which job, if any, an interview was taken for. NULL for every
-- interview a candidate starts on their own, including all of them
-- before this migration.
ALTER TABLE interview_sessions
    ADD COLUMN job_posting_id bigint;

-- Deleting a job must not delete the candidate's own interview record;
-- it just stops being shared.
ALTER TABLE interview_sessions
    ADD CONSTRAINT fk_interview_sessions_job_posting
        FOREIGN KEY (job_posting_id) REFERENCES job_postings (id) ON DELETE SET NULL;

CREATE INDEX idx_interview_sessions_job_posting
    ON interview_sessions (job_posting_id);
